export type Course = {
  id: string;
  code: string;
  title: string;
  description: string;
  creator: string;
  origin: 'admin' | 'student';
  recognised: boolean;
  color: string;
  icon: 'database' | 'code' | 'cpu' | 'math';
};
export type Material = {
  id: string;
  courseId: string;
  title: string;
  pages: number;
  fileName: string;
  uri?: string;
  sample: boolean;
  status: 'ready' | 'processing' | 'failed';
};
export type Comment = {
  id: string;
  author: string;
  ownerId: string;
  anonymous: boolean;
  body: string;
  parentId?: string;
};
export type Post = {
  id: string;
  courseId: string;
  author: string;
  ownerId: string;
  anonymous: boolean;
  title: string;
  body: string;
  tag: 'Question' | 'Study tip' | 'Discussion';
  score: number;
  createdAt: number;
  comments: Comment[];
};
export type Profile = {
  name: string;
  email: string;
  department: string;
  year: number;
  admin: boolean;
};
export type Attempt = {
  id: string;
  courseId: string;
  materialId: string;
  correct: number;
  total: number;
  missed: number[];
  createdAt: number;
};
export type LocalData = {
  version: 1;
  profile: Profile;
  session: boolean;
  onboarded: boolean;
  courses: Course[];
  joined: string[];
  materials: Material[];
  posts: Post[];
  votes: Record<string, -1 | 0 | 1>;
  saved: string[];
  attempts: Attempt[];
  reminders: boolean;
  blocked: string[];
};
